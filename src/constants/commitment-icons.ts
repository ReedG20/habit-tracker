/**
 * The glyph a habit or goal wears: its own icon, or the kind's default for
 * one made before icons existed (or with a key this build doesn't know).
 */
export function commitmentIcon(
  key: string | undefined | null,
  kind: 'habit' | 'goal',
): IconSvgElement {
  if (key != null && isCommitmentIconKey(key)) return COMMITMENT_ICON_SVGS[key];
  return kind === 'habit' ? HabitIcon : GoalListIcon;
}
